export function glyph(ch: string): readonly number[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS["?"];
}

export function pixelText(
  fb: Fb,
  text: string,
  x: number,
  y: number,
  height: number,
  color: number,
  advance = (height * 6) / 7,
): void {
  const unit = height / 7;
  for (const [i, ch] of [...text].entries())
    for (const [row, bits] of glyph(ch).entries())
      for (let col = 0; col < 5; col++) {
        if (bits & (1 << (4 - col)))
          fb.rect(
            x + i * advance + col * unit,
            y + row * unit,
            Math.max(1, unit),
            Math.max(1, unit),
            color,
          );
      }
}
